<?php
// One-time installer: writes app/config.php, creates tables and the first admin account.
// It locks itself once an admin exists. Delete this file after installing.
declare(strict_types=1);
require __DIR__ . '/app/bootstrap.php';

$configFile = APP_DIR . '/config.php';
$hasConfig = is_file($configFile);
$errors = [];
$done = false;
$configText = '';

function admin_exists(): bool {
    try { return (int)db()->query('SELECT COUNT(*) FROM sms_admins')->fetchColumn() > 0; }
    catch (Throwable $e) { return false; }
}

function run_schema(PDO $pdo): void {
    $sql = (string)file_get_contents(APP_DIR . '/schema.sql');
    $sql = preg_replace('/^\s*--.*$/m', '', $sql);
    foreach (array_filter(array_map('trim', explode(';', $sql))) as $stmt) $pdo->exec($stmt);
}

if ($hasConfig && admin_exists()) {
    page_header('Installed');
    echo '<section class="card"><h1>Already installed</h1><p>An admin account exists, so the installer is locked.</p>';
    echo '<p><b>Delete <code>install.php</code> from your server</b>, then <a href="login.php">log in</a>.</p></section>';
    page_footer();
    exit;
}

$v = [
    'db_host' => 'localhost', 'db_port' => '3306', 'db_name' => '', 'db_user' => '', 'db_pass' => '',
    'timezone' => 'Asia/Karachi', 'username' => 'admin',
];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    csrf_check();
    foreach ($v as $k => $_) if (isset($_POST[$k])) $v[$k] = trim((string)$_POST[$k]);
    $password = (string)($_POST['password'] ?? '');

    if (!preg_match('/^[A-Za-z0-9_.-]{3,60}$/', $v['username'])) $errors[] = 'Username: 3–60 letters, numbers, dot, dash or underscore.';
    if (strlen($password) < 8) $errors[] = 'Password must be at least 8 characters.';
    if (!in_array($v['timezone'], DateTimeZone::listIdentifiers(), true)) $errors[] = 'Unknown timezone (example: Asia/Karachi).';

    if (!$errors) {
        try {
            if ($hasConfig) {
                $pdo = db();
            } else {
                $dsn = sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $v['db_host'], (int)$v['db_port'], $v['db_name']);
                $pdo = new PDO($dsn, $v['db_user'], $v['db_pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            }
            run_schema($pdo);
            if ((int)$pdo->query('SELECT COUNT(*) FROM sms_admins')->fetchColumn() > 0) {
                $errors[] = 'An admin already exists in this database.';
            } else {
                $pdo->prepare('INSERT INTO sms_admins(username, password_hash, created_at) VALUES(?,?,UTC_TIMESTAMP())')
                    ->execute([$v['username'], password_hash($password, PASSWORD_DEFAULT)]);
                if (!$hasConfig) {
                    $cfg = [
                        'db_host' => $v['db_host'], 'db_port' => (int)$v['db_port'], 'db_name' => $v['db_name'],
                        'db_user' => $v['db_user'], 'db_pass' => $v['db_pass'],
                        'app_name' => 'SMS Gateway', 'timezone' => $v['timezone'], 'require_https' => true, 'country_code' => '92',
                        'max_pending' => 20, 'daily_limit' => 100, 'max_message' => 160,
                    ];
                    $configText = "<?php\n// Generated by install.php — see config.sample.php for all options.\nreturn " . var_export($cfg, true) . ";\n";
                    if (@file_put_contents($configFile, $configText) !== false) {
                        @chmod($configFile, 0640);
                        $configText = '';
                    }
                }
                $done = true;
            }
        } catch (PDOException $e) {
            $errors[] = 'Database error: ' . $e->getMessage();
        }
    }
}

page_header('Install');
if ($done): ?>
<section class="card">
  <h1>Installed ✓</h1>
  <?php if ($configText): ?>
    <p class="alert">The server did not allow writing <code>app/config.php</code>. Create that file yourself with this content:</p>
    <textarea rows="16" readonly class="mono"><?=e($configText)?></textarea>
  <?php endif; ?>
  <ol>
    <li><b>Delete <code>install.php</code></b> from your server.</li>
    <li><a href="login.php">Log in</a> as <b><?=e($v['username'])?></b>.</li>
    <li>Add your Android phone and copy its device key into the app.</li>
  </ol>
</section>
<?php else: ?>
<section class="card narrow">
  <h1>Install SMS Gateway</h1>
  <?php foreach ($errors as $err): ?><p class="alert"><?=e($err)?></p><?php endforeach; ?>
  <?php if (!is_https()): ?><p class="alert">This page is not on HTTPS. The Android app only connects over HTTPS — enable SSL (free AutoSSL / Let's Encrypt in cPanel) before using it.</p><?php endif; ?>
  <form method="post">
    <?=csrf_field()?>
    <?php if (!$hasConfig): ?>
      <h2>Database</h2>
      <p class="muted">Create a MySQL database and user in cPanel → MySQL Databases first.</p>
      <div class="row2"><label>Host<input name="db_host" value="<?=e($v['db_host'])?>" required></label><label>Port<input name="db_port" value="<?=e($v['db_port'])?>" required></label></div>
      <label>Database name<input name="db_name" value="<?=e($v['db_name'])?>" required></label>
      <label>Database user<input name="db_user" value="<?=e($v['db_user'])?>" required></label>
      <label>Database password<input type="password" name="db_pass" value="<?=e($v['db_pass'])?>"></label>
      <label>Timezone (for showing times)<input name="timezone" value="<?=e($v['timezone'])?>" required></label>
    <?php else: ?>
      <p class="muted">Using the database from <code>app/config.php</code>.</p>
      <input type="hidden" name="timezone" value="<?=e((string)config('timezone'))?>">
    <?php endif; ?>
    <h2>Admin account</h2>
    <label>Username<input name="username" value="<?=e($v['username'])?>" required autocomplete="username"></label>
    <label>Password (8+ characters)<input type="password" name="password" required minlength="8" autocomplete="new-password"></label>
    <button type="submit">Install</button>
  </form>
</section>
<?php endif;
page_footer();
